import { siteDemo } from "@/config/site-demo";
import { type Accent, accentParam, resolveAccent } from "@/lib/color";

/**
 * Personalization from the URL: only the city and accent color. The business name is always the
 * generic demo name (Bosko, 2026-10-04: no business names, so visitors know it's just a demo). The phone number and AI assistant can never be overridden from a link; otherwise
 * anyone could put their own number on our domain.
 */
export type Brand = {
  /** Always siteDemo.business.name; kept on the type so the logo and copy have one source. */
  name: string;
  /** null = the default service-area list is shown instead of one custom city. */
  city: string | null;
  accent: Accent;
};

export const MAX_NAME = 40;
export const MAX_CITY = 30;

const LOOKS_LIKE_LINK = /https?:|www\.|\.(com|net|org|io|co|us|info|biz|xyz|app|dev|ru|cn)\b|@|\/\//i;

function clean(raw: unknown, allowed: RegExp, max: number) {
  const value = Array.isArray(raw) ? raw[0] : raw;
  if (typeof value !== "string") return null;
  const normalized = value.normalize("NFKC").replace(/\p{C}/gu, "");
  if (LOOKS_LIKE_LINK.test(normalized)) return null;
  const kept = normalized.replace(allowed, "").replace(/\s+/g, " ").trim().slice(0, max).trim();
  return kept.length >= 2 ? kept : null;
}

/** Letters (any language), digits, spaces and & ' . , - ! only. Used for the names in lead alerts. */
export function cleanBusinessName(raw: unknown) {
  return clean(raw, /[^\p{L}\p{M}\p{N} &'’.,!-]/gu, MAX_NAME);
}

/** Letters, spaces and . ' - only. */
export function cleanCity(raw: unknown) {
  return clean(raw, /[^\p{L}\p{M} .'’-]/gu, MAX_CITY);
}

type Params = Record<string, string | string[] | undefined>;

export function resolveBrand(params: Params): Brand {
  const color = params.color;
  return {
    name: siteDemo.business.name,
    city: cleanCity(params.city),
    accent: resolveAccent(Array.isArray(color) ? color[0] : color, siteDemo.accent),
  };
}

export function isDefaultBrand(brand: Brand) {
  return brand.name === siteDemo.business.name && brand.city === null && brand.accent.key === siteDemo.accent;
}

/** Query string for a shareable demo link (empty for the default demo). */
export function brandQuery(brand: Brand) {
  const query = new URLSearchParams();
  if (brand.city) query.set("city", brand.city);
  if (brand.accent.key !== siteDemo.accent) query.set("color", accentParam(brand.accent));
  const text = query.toString();
  return text ? `?${text}` : "";
}

/** Up to two initials, skipping filler words, for the serif monogram logo. */
export function initials(name: string) {
  const words = name
    .split(/[\s-]+/)
    .filter((word) => /[\p{L}\p{N}]/u.test(word) && !/^(&|and|the|of|co\.?|llc|inc\.?)$/i.test(word));
  const letters = words.slice(0, 2).map((word) => [...word.replace(/[^\p{L}\p{N}]/gu, "")][0] ?? "");
  return letters.join("").toUpperCase() || "·";
}

/** CSS that sets the accent variables for both light and dark mode. Values are generated by
 *  lib/color.ts (hex or oklch numbers only), never raw visitor text. */
export function accentCss(accent: Accent) {
  return `:root{--brand-light:${accent.light};--brand-dark:${accent.dark}}`;
}
